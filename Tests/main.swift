import Foundation

func check(_ condition: @autoclosure () -> Bool, _ message: String) {
    if !condition() { fatalError(message) }
}
let origin = Date(timeIntervalSince1970: 1_800_000_000)
var clock = TimerEngine()
clock.start(at: origin)
check(clock.advance(to: origin.addingTimeInterval(2400)) == 1, "focus boundary")
check(clock.phase == .rest && clock.remaining == 300, "rest starts automatically")
clock.advance(to: origin.addingTimeInterval(2700))
check(clock.phase == .focus && clock.remaining == 2400, "focus resumes automatically")
clock.pause(at: origin.addingTimeInterval(2800))
check(clock.remaining == 2300 && !clock.running, "pause preserves remainder")
clock.start(at: origin.addingTimeInterval(4000))
clock.advance(to: origin.addingTimeInterval(4001))
check(clock.remaining == 2299, "resume excludes paused time")
clock.reset(at: origin.addingTimeInterval(4001))
check(clock.remaining == 2400 && !clock.running, "reset")
clock.start(at: origin)
clock.advance(to: origin.addingTimeInterval(2700 * 3 + 50))
check(clock.phase == .focus && clock.remaining == 2350, "wake after multiple cycles")
check(clock.completed.count == 4, "count only completed focus sessions")
let data = try JSONEncoder().encode(clock)
let restored = try JSONDecoder().decode(TimerEngine.self, from: data)
check(restored.deadline == clock.deadline, "restart restores absolute deadline")
clock.skip()
check(clock.phase == .rest && !clock.running && clock.remaining == 300, "skip does not count completion")
print("Passed: boundaries, automatic cycle, pause/resume, sleep recovery, persistence, skip")

var ledger = TimerEngine()
ledger.start(at: origin)
ledger.pause(at: origin.addingTimeInterval(120))
ledger.start(at: origin.addingTimeInterval(600))
ledger.endFocus(at: origin.addingTimeInterval(660))
check(ledger.spans.reduce(0) { $0 + $1.duration } == 180, "pause time excluded from ledger")
check(ledger.completed.isEmpty && ledger.earlyEnds.count == 1, "early ending is not a complete round")
check(ledger.phase == .rest && ledger.deadline == origin.addingTimeInterval(960), "early finish starts five minute rest")
ledger.advance(to: origin.addingTimeInterval(960))
check(ledger.phase == .focus && ledger.running, "automatic focus after early finish rest")
let midnight = Calendar.current.startOfDay(for: origin)
var crossing = TimerEngine()
crossing.start(at: midnight.addingTimeInterval(-60))
crossing.pause(at: midnight.addingTimeInterval(120))
check(crossing.todayFocusSeconds(at: midnight.addingTimeInterval(121)) == 120, "cross midnight split")
check(crossing.todayFocusSeconds(at: midnight.addingTimeInterval(-1)) == 60, "previous day split")
var live = TimerEngine()
live.start(at: midnight.addingTimeInterval(100))
check(live.todayFocusSeconds(at: midnight.addingTimeInterval(150)) == 50, "live focus counted")
live.pause(at: midnight.addingTimeInterval(150))
check(live.todayFocusSeconds(at: midnight.addingTimeInterval(500)) == 50, "paused ledger does not grow")
live.endFocus(at: midnight.addingTimeInterval(500))
check(live.phase == .rest && !live.running, "paused early ending stays paused")
let oldJSON = "{\"phase\":\"focus\",\"remaining\":2400,\"completed\":[10000]}".data(using: .utf8)!
let migrated = try JSONDecoder().decode(TimerEngine.self, from: oldJSON)
check(migrated.spans.count == 1 && migrated.spans[0].duration == 2400, "legacy migration retains completed time")
let roundtrip = try JSONDecoder().decode(TimerEngine.self, from: JSONEncoder().encode(ledger))
check(roundtrip.spans.count == ledger.spans.count && roundtrip.activeStart == ledger.activeStart, "ledger persists")
print("Passed: actual focus ledger, pause exclusion, early ending, midnight split, live totals, legacy migration")

var shorter = TimerEngine()
shorter.setFocusMinutes(25, at: origin)
check(shorter.remaining == 1500, "idle duration changes immediately")
shorter.start(at: origin)
shorter.advance(to: origin.addingTimeInterval(600))
shorter.setFocusMinutes(30, at: origin.addingTimeInterval(600))
check(shorter.remaining == 1200, "duration change preserves elapsed focus")
shorter.advance(to: origin.addingTimeInterval(1800))
check(shorter.phase == .rest && shorter.remaining == 300, "selected duration ends correctly")
shorter.advance(to: origin.addingTimeInterval(2100))
check(shorter.phase == .focus && shorter.remaining == 1800, "new cycle uses selected duration")
var reached = TimerEngine()
reached.start(at: origin)
reached.setFocusMinutes(25, at: origin.addingTimeInterval(1600))
check(reached.phase == .rest && reached.remaining == 300, "shortening beyond elapsed starts rest")
check(reached.spans.reduce(0) { $0 + $1.duration } == 1600, "shortened session retains actual duration")
let selectedRestored = try JSONDecoder().decode(TimerEngine.self, from: JSONEncoder().encode(shorter))
check(selectedRestored.focusMinutes == 30, "selected focus duration persists")
print("Passed: configurable focus duration, elapsed preservation, automatic cycles, shortened session, persistence")
